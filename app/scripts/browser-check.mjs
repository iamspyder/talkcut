import {chromium} from 'playwright-core';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const base=process.env.TALKCUT_URL||'http://127.0.0.1:5173';
const fixture=JSON.parse(await fs.readFile(path.join(root,'data','seed','project.json'),'utf8'));fixture.id=crypto.randomUUID();fixture.name='QA editor '+Date.now();fixture.demo=false;fixture.compositions=fixture.compositions.slice(0,1);fixture.compositions[0].id=crypto.randomUUID();fixture.compositions[0].captions=false;fixture.compositions[0].aspect='16:9';delete fixture.revision;await fetch(base+'/api/projects',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(fixture)});
await fs.mkdir(path.join(root,'qa'),{recursive:true});
const browser=await chromium.launch({channel:'chrome',executablePath:process.env.CHROME_PATH||undefined,headless:true});
const errors=[];
const page=await browser.newPage({viewport:{width:1512,height:982},deviceScaleFactor:1});
page.on('pageerror',e=>errors.push(e.message));
try{
 await page.route('**/api/projects',async route=>{
  if(route.request().method()!=='GET')return route.continue();
  const response=await route.fetch();const projects=await response.json();
  await route.fulfill({response,json:projects.filter(p=>p.id===fixture.id)});
 });
 await page.goto(process.env.TALKCUT_URL||'http://127.0.0.1:5173',{waitUntil:'networkidle'});
 if(await page.getByRole('button',{name:'Dismiss tour',exact:true}).count())await page.getByRole('button',{name:'Dismiss tour',exact:true}).click();
 await page.locator('.word').first().waitFor();
 await page.screenshot({path:path.join(root,'qa','desktop.png'),fullPage:true});
 assert.match(await page.title(),/TalkCut/);
 const original=await page.locator('.word').count();
 await page.locator('.word').nth(1).click();
 await page.keyboard.press('Delete');
 assert.equal(await page.locator('.word').count(),original-1);
 await page.getByRole('button',{name:'Undo (Ctrl+Z)',exact:true}).click();
 assert.equal(await page.locator('.word').count(),original);
 await page.locator('.word').first().dblclick();
 await page.getByRole('textbox',{name:'Selected text'}).fill('Each');
 await page.getByRole('button',{name:'Correct text',exact:true}).click();
 assert.equal(await page.locator('.word').first().textContent(),'Each');
 await page.getByRole('button',{name:'Undo (Ctrl+Z)',exact:true}).click();
 assert.equal(await page.locator('.word').first().textContent(),'Every');
 await page.locator('.word').first().click();
 await page.locator('.word').nth(2).click({modifiers:['Control']});
 await page.keyboard.press('c');
 await page.getByRole('textbox',{name:'Selected text'}).fill('A discontinuous edit');
 await page.getByRole('button',{name:'Correct text',exact:true}).click();
 assert.equal(await page.locator('.error-toast').count(),1,'discontinuous correction must be rejected without crashing');
 await page.getByRole('button',{name:'Dismiss error',exact:true}).click();
 await page.getByRole('button',{name:'Close dialog',exact:true}).click();
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:'Play composition',exact:true}).click();
 await page.waitForTimeout(1800);
 const videoTime=await page.locator('video').evaluate(v=>v.currentTime);
 assert.ok(videoTime>0.5,'video should actually play');
 await page.getByRole('button',{name:'Pause playback',exact:true}).click();
 await page.locator('.tool-rail').getByRole('button',{name:'Captions',exact:true}).click();
 await page.getByRole('button',{name:'Toggle captions',exact:true}).click();
 assert.equal(await page.getByRole('button',{name:'Toggle captions',exact:true}).getAttribute('aria-pressed'),'true');
 await page.waitForTimeout(1000);
 await page.reload({waitUntil:'networkidle'});
 await page.locator('.word').first().waitFor();
 await page.locator('.tool-rail').getByRole('button',{name:'Captions',exact:true}).click();
 assert.equal(await page.getByRole('button',{name:'Toggle captions',exact:true}).getAttribute('aria-pressed'),'true','caption state should persist');
 await page.getByRole('button',{name:'Toggle captions',exact:true}).click();
 await page.locator('.tool-rail').getByRole('button',{name:'Scene',exact:true}).click();
 await page.getByRole('button',{name:'9:16',exact:true}).click();
 assert.equal(await page.locator('.ratio-9-16').count(),1);
 await page.getByRole('button',{name:'16:9',exact:true}).click();
 await page.locator('.tool-rail').getByRole('button',{name:'Cleanup',exact:true}).click();
 await page.getByRole('button',{name:'Remove filler words',exact:true}).click();
 await page.locator('.cleanup-report').waitFor(); assert.ok(await page.locator('.word').count()<original,'one-click filler cleanup cuts words');
 await page.getByRole('button',{name:'Undo (Ctrl+Z)',exact:true}).click();
 await page.screenshot({path:path.join(root,'qa','desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Close tools panel',exact:true}).click();
 await page.screenshot({path:path.join(root,'qa','mobile.png'),fullPage:true});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 assert.equal(overflow,false,'mobile viewport must not overflow horizontally');
 assert.deepEqual(errors,[],'no browser runtime errors');
 await fs.writeFile(path.join(root,'qa','browser-results.json'),JSON.stringify({passed:true,checks:['Transcript deletion','Undo','Correct text without media cuts','Reject discontinuous correction without crashing','Actual media playback','Caption state persisted after reload','Aspect ratio change','One-click filler cleanup and undo','Mobile without horizontal overflow'],runtimeErrors:errors},null,2));
 console.log('Browser checks passed:',original,'words; playback at',videoTime.toFixed(2),'seconds.');
}catch(e){await page.screenshot({path:path.join(root,'qa','failure.png'),fullPage:true});await fs.writeFile(path.join(root,'qa','browser-results.json'),JSON.stringify({passed:false,error:e.message,runtimeErrors:errors},null,2));throw e;}finally{await browser.close();}
